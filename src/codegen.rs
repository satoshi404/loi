//! C backend for Loi.
//!
//! The backend lowers a checked [`Program`] to a single C translation unit. It
//! owns no type inference of its own beyond what it needs to spell C types and
//! choose between value and pointer representations.
//!
//! Representation choices:
//!
//! - `in` parameters are passed by value (scalars, interfaces and slice
//!   headers). The checker already forbids storing or returning borrowed
//!   values; C copying is an implementation detail.
//! - `out` and `inout` parameters are passed by pointer in C.
//! - Slices are `{ void* data; size_t len; }`; indexing casts the element type
//!   and goes through a bounds check.
//! - Every `protect` block saves and restores a single bump-arena offset.
//!   Allocations made by callees use the nearest caller arena because the arena
//!   is global.

use std::collections::{HashMap, HashSet};
use std::fmt;
use std::path::Path;

use crate::ast::*;
