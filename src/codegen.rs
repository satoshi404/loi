/// How a variable is represented in generated C.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Repr {
    Value,
    Pointer,
}

#[derive(Debug, Clone)]
struct VarInfo {
    ty: Ty,
    repr: Repr,
}

/// A mapping from a position in generated C back to a position in the source
/// Loi file.
#[derive(Debug, Clone)]
struct SourceMapEntry {
    c_line: usize,
    c_column: usize,
    loi_line: usize,
    loi_column: usize,
    kind: String,
}

struct Generator<'a> {
    interfaces: HashMap<String, &'a InterfaceDecl>,
    /// Foreign handle names declared with `opaque`.
    opaques: HashSet<String>,
    functions: HashMap<String, &'a FunctionDecl>,
    globals: HashMap<String, &'a GlobalDecl>,
    global_order: Vec<String>,
    /// When set, only these declarations are defined in the output; the rest
    /// are emitted as external declarations (multi-file builds).
    defined: Option<std::collections::HashSet<String>>,
    /// Decoded string literals and their static array index.
    strings: HashMap<String, usize>,
    string_order: Vec<String>,
    intrinsic_return_ty: HashMap<String, Ty>,
    interface_order: Vec<String>,
    function_order: Vec<String>,
    out: String,
    depth: usize,
    temp_counter: usize,
    scopes: Vec<HashMap<String, VarInfo>>,
    protect_saves: Vec<String>,
    loop_bases: Vec<usize>,
    current_function: String,
    source_map_path: Option<&'a Path>,
    source_map_entries: Vec<SourceMapEntry>,
}

impl<'a> Generator<'a> {
    fn new(
        program: &'a Program,
        source_map_path: Option<&'a Path>,
        defined: Option<std::collections::HashSet<String>>,
    ) -> Self {
        let mut interfaces = HashMap::new();
        let mut opaques = HashSet::new();
        let mut functions = HashMap::new();
        let mut globals = HashMap::new();
        let mut global_order = Vec::new();
        let mut intrinsic_return_ty = HashMap::new();
        let mut interface_order = Vec::new();
        let mut function_order = Vec::new();

        // Intrinsics map to C library calls; they are not user functions and
        // have no AST declaration, so their signatures are tracked separately.
        intrinsic_return_ty.insert("print".to_string(), Ty::Void);
        intrinsic_return_ty.insert("eprint".to_string(), Ty::Void);
        intrinsic_return_ty.insert("panic".to_string(), Ty::Void);
        intrinsic_return_ty.insert("sqrt".to_string(), Ty::F64);
        intrinsic_return_ty.insert("floor".to_string(), Ty::F64);
        intrinsic_return_ty.insert("ceil".to_string(), Ty::F64);
        intrinsic_return_ty.insert("pow".to_string(), Ty::F64);
        intrinsic_return_ty.insert("fabs".to_string(), Ty::F64);
        intrinsic_return_ty.insert("fmod".to_string(), Ty::F64);
        intrinsic_return_ty.insert("len".to_string(), Ty::U64);

        for item in &program.items {
            match item {
                Item::Import(_) => {}
                Item::Interface(decl) => {
                    if !interfaces.contains_key(&decl.name) {
                        interfaces.insert(decl.name.clone(), decl);
                        interface_order.push(decl.name.clone());
                    }
                }
                Item::Opaque(decl) => {
                    opaques.insert(decl.name.clone());
                }
                Item::Global(decl) => {
                    if !globals.contains_key(&decl.name) {
                        globals.insert(decl.name.clone(), decl);
                        global_order.push(decl.name.clone());
                    }
                }
                Item::Function(decl) => {
                    if !functions.contains_key(&decl.name) {
                        functions.insert(decl.name.clone(), decl);
                        function_order.push(decl.name.clone());
                    }
                }
            }
        }

        let mut strings = HashMap::new();
        let mut string_order = Vec::new();
        collect_program_strings(program, &mut strings, &mut string_order);

        Self {
            interfaces,
            opaques,
            functions,
            globals,
            global_order,
            defined,
            strings,
            string_order,
            intrinsic_return_ty,
            interface_order,
            function_order,
            out: String::new(),
            depth: 0,
            temp_counter: 0,
            scopes: Vec::new(),
            protect_saves: Vec::new(),
            loop_bases: Vec::new(),
            current_function: String::new(),
            source_map_path,
            source_map_entries: Vec::new(),
        }
    }

    fn generate(mut self) -> Result<String, CodegenError> {
        if let Some(main) = self.functions.get("main").copied() {
            if !main.params.is_empty() {
                return Err(CodegenError::new(
                    "the C backend requires 'main' to have no parameters",
                ));
            }
            if let Some(return_type) = &main.return_type {
                let ty = self.resolve_type(return_type);
                if !ty.is_integer() {
                    return Err(CodegenError::new(
                        "the C backend requires 'main' to return no value or an integer",
                    ));
                }
            }
        }

        self.interface_order = self.compute_interface_order()?;

        self.out.push_str(PRELUDE);
        self.out.push('\n');
        self.emit_interfaces();
        self.emit_strings();
        self.emit_globals();
        self.emit_prototypes();
        self.emit_functions();

        if let Some(map_path) = self.source_map_path {
            self.write_source_map(map_path)?;
        }

        Ok(self.out)
    }

    /// Write the collected source map entries as JSON Lines to `path`.
    fn write_source_map(&self, path: &Path) -> Result<(), CodegenError> {
        use std::fmt::Write;
        let mut content = String::new();
        for entry in &self.source_map_entries {
            let _ = writeln!(
                content,
                "{{\"c_line\":{}, \"c_column\":{}, \"loi_line\":{}, \"loi_column\":{}, \"kind\":\"{}\"}}",
                entry.c_line, entry.c_column, entry.loi_line, entry.loi_column, entry.kind
            );
        }
        std::fs::write(path, content).map_err(|e| {
            CodegenError::new(format!(
                "failed to write source map '{}': {e}",
                path.display()
            ))
        })?;
        Ok(())
    }

    /// Emit only declarations for `visible` items into a C header.
    fn generate_header(mut self) -> Result<String, CodegenError> {
        self.interface_order = self.compute_interface_order()?;

        let header_name = self
            .functions
            .get("main")
            .map(|_| "LOI_MAIN_H")
            .unwrap_or("LOI_H");

        self.emit(format!("#ifndef {header_name}"));
        self.emit(format!("#define {header_name}"));
        self.emit("");
        self.emit("#include <stdbool.h>");
        self.emit("#include <stddef.h>");
        self.emit("#include <stdint.h>");
        self.emit("");
        self.emit("/* Intrinsics */");
        self.emit("void loi_fn_print(void* data, size_t len);");
        self.emit("double loi_fn_sqrt(double x);");
        self.emit("");
        self.emit_interfaces_visible();
        self.emit_prototypes_visible();
        self.emit("");
        self.emit("#endif");

        if let Some(map_path) = self.source_map_path {
            self.write_source_map(map_path)?;
        }

        Ok(self.out)
    }

    // ------------------------------------------------------------------
    // Small output helpers
    // ------------------------------------------------------------------

    fn emit(&mut self, line: impl AsRef<str>) {
        for _ in 0..self.depth {
            self.out.push_str("    ");
        }
        self.out.push_str(line.as_ref());
        self.out.push('\n');
    }

    /// Emits a line with an inline `// loi:line:col` comment and records a
    /// source map entry mapping the generated C position to the source Loi
    /// position. Only records when `source_map_path` is set.
    fn emit_with_span(&mut self, line: impl AsRef<str>, span: Span, kind: &str) {
        let c_line = self.out.chars().filter(|&c| c == '\n').count() + 1;
        let c_column = self.out.lines().next_back().map_or(1, |l| l.len() + 1);
        self.emit(format!(
            "{}  // loi:{}:{}",
            line.as_ref(),
            span.line,
            span.column
        ));
        if self.source_map_path.is_some() {
            self.source_map_entries.push(SourceMapEntry {
                c_line,
                c_column,
                loi_line: span.line,
                loi_column: span.column,
                kind: kind.to_string(),
            });
        }
    }

    fn emit_open(&mut self, prefix: &str) {
        if prefix.is_empty() {
            self.emit("{");
        } else {
            self.emit(format!("{prefix} {{"));
        }
        self.depth += 1;
    }

    fn emit_close(&mut self) {
        self.depth -= 1;
        self.emit("}");
    }

    fn fresh(&mut self, hint: &str) -> String {
        self.temp_counter += 1;
        format!("loi_tmp_{hint}_{}", self.temp_counter)
    }

    // ------------------------------------------------------------------
    // Names
    // ------------------------------------------------------------------

    fn c_local(&self, name: &str) -> String {
        format!("loi_v_{name}")
    }

    fn c_global(&self, name: &str) -> String {
        format!("loi_g_{name}")
    }

    fn c_func(&self, name: &str) -> String {
        if name == "main" {
            return "main".to_string();
        }
        if let Some(decl) = self.functions.get(name)
            && decl.external
        {
            return decl.link_name.clone().unwrap_or_else(|| name.to_string());
        }
        format!("loi_fn_{name}")
    }

    fn c_interface(&self, name: &str) -> String {
        format!("loi_t_{name}")
    }

    fn c_field(&self, name: &str) -> String {
        format!("loi_f_{name}")
    }

    // ------------------------------------------------------------------
    // Types and declarations
    // ------------------------------------------------------------------

    fn resolve_type(&self, ty: &Type) -> Ty {
        match ty {
            Type::Named(name) => {
                if let Some(primitive) = Ty::from_name(name) {
                    primitive
                } else if name == "cstr" {
                    Ty::CStr
                } else if self.opaques.contains(name) {
                    Ty::Opaque(name.clone())
                } else {
                    Ty::Named(name.clone())
                }
            }
            Type::Slice(element) => Ty::Slice(Box::new(self.resolve_type(element))),
        }
    }

    fn c_type(&self, ty: &Ty) -> String {
        match ty {
            Ty::I8 => "int8_t".to_string(),
            Ty::I16 => "int16_t".to_string(),
            Ty::I32 => "int32_t".to_string(),
            Ty::I64 => "int64_t".to_string(),
            Ty::U8 => "uint8_t".to_string(),
            Ty::U16 => "uint16_t".to_string(),
            Ty::U32 => "uint32_t".to_string(),
            Ty::U64 => "uint64_t".to_string(),
            Ty::F32 => "float".to_string(),
            Ty::F64 => "double".to_string(),
            Ty::Bool => "bool".to_string(),
            Ty::Named(name) => self.c_interface(name),
            Ty::Opaque(_) => "void *".to_string(),
            Ty::CStr => "const char *".to_string(),
            Ty::Slice(_) => "LoiSlice".to_string(),
            Ty::IntLiteral => "int32_t".to_string(),
            Ty::FloatLiteral => "double".to_string(),
            Ty::Void => "void".to_string(),
            Ty::Error => "void".to_string(),
        }
    }

    fn compute_interface_order(&self) -> Result<Vec<String>, CodegenError> {
        let mut order = Vec::new();
        let mut state: HashMap<String, u8> = HashMap::new();
        for name in &self.interface_order {
            self.visit_interface(name, &mut state, &mut order)?;
        }
        Ok(order)
    }

    fn visit_interface(
        &self,
        name: &str,
        state: &mut HashMap<String, u8>,
        order: &mut Vec<String>,
    ) -> Result<(), CodegenError> {
        match state.get(name).copied().unwrap_or(0) {
            2 => return Ok(()),
            1 => {
                return Err(CodegenError::new(format!(
                    "shape '{name}' contains itself by value"
                )));
            }
            _ => {}
        }

        state.insert(name.to_string(), 1);
        if let Some(decl) = self.interfaces.get(name).copied() {
            for field in &decl.fields {
                if let Type::Named(dependency) = &field.ty
                    && self.interfaces.contains_key(dependency)
                {
                    self.visit_interface(dependency, state, order)?;
                }
            }
        }
        state.insert(name.to_string(), 2);
        order.push(name.to_string());
        Ok(())
    }

    fn emit_interfaces(&mut self) {
        let order = self.interface_order.clone();

        for name in &order {
            let Some(decl) = self.interfaces.get(name).copied() else {
                continue;
            };
            let ty = self.c_interface(name);
            self.emit_with_span(format!("typedef struct {ty} {ty};"), decl.span, "interface");
        }
        self.emit("");

        for name in &order {
            let Some(decl) = self.interfaces.get(name).copied() else {
                continue;
            };
            let ty = self.c_interface(name);
            self.emit_with_span(format!("struct {ty} {{"), decl.span, "interface");
            self.depth += 1;
            if decl.fields.is_empty() {
                self.emit("unsigned char loi_f_empty;");
            }
            for field in &decl.fields {
                let field_ty = self.resolve_type(&field.ty);
                self.emit(format!(
                    "{} {};",
                    self.c_type(&field_ty),
                    self.c_field(&field.name)
                ));
            }
            self.depth -= 1;
            self.emit("};");
            self.emit("");
        }
    }

    /// Emit static byte arrays for every string literal in the program.
    fn emit_strings(&mut self) {
        if self.string_order.is_empty() {
            return;
        }
        let strings = self.string_order.clone();
        for (index, text) in strings.iter().enumerate() {
            let bytes = text.as_bytes();
            let values = if bytes.is_empty() {
                "0".to_string()
            } else {
                let bytes = bytes
                    .iter()
                    .map(|byte| byte.to_string())
                    .collect::<Vec<_>>()
                    .join(", ");
                // Always keep a trailing NUL so the same literal can be used
                // as a `cstr` at the FFI boundary. The slice length excludes it.
                format!("{bytes}, 0")
            };
            self.emit(format!(
                "static unsigned char loi_str_{index}[] = {{ {values} }};"
            ));
        }
        self.emit("");
    }

    /// Emit top-level `let`/`var` declarations as C globals.
    ///
    /// In a subset build (multi-file), globals owned by other translation units
    /// become `extern` declarations instead of definitions.
    fn emit_globals(&mut self) {
        let order = self.global_order.clone();
        let mut emitted = false;
        for name in &order {
            let Some(decl) = self.globals.get(name).copied() else {
                continue;
            };
            let c_name = self.c_global(name);
            let local = self
                .defined
                .as_ref()
                .is_none_or(|defined| defined.contains(name));
            let ty = decl
                .ty
                .as_ref()
                .map(|ty| self.resolve_type(ty))
                .unwrap_or_else(|| self.ty_of(&decl.value).concretize());
            let c_ty = self.c_type(&ty);
            if local {
                let initializer = self.global_initializer(&ty, &decl.value);
                self.emit(format!("{c_ty} {c_name} = {initializer};"));
            } else {
                self.emit(format!("extern {c_ty} {c_name};"));
            }
            emitted = true;
        }
        if emitted {
            self.emit("");
        }
    }

    fn global_initializer(&mut self, ty: &Ty, value: &Expr) -> String {
        if matches!(ty, Ty::CStr) {
            return self.gen_coerced_expr(value, ty);
        }
        match &value.kind {
            ExprKind::String(text) => {
                let index = self.string_index(text);
                format!("{{ (void*)loi_str_{index}, {} }}", text.len())
            }
            _ => self.gen_expr(value),
        }
    }

    fn string_index(&self, text: &str) -> usize {
        *self
            .strings
            .get(text)
            .expect("string literal should have been collected")
    }

    /// Emit interface declarations for `visible` interfaces only.
    fn emit_interfaces_visible(&mut self) {
        let order = self.interface_order.clone();
        for name in &order {
            let Some(decl) = self.interfaces.get(name).copied() else {
                continue;
            };
            if decl.visibility != Visibility::Visible {
                continue;
            }
            let ty = self.c_interface(name);
            self.emit_with_span(format!("typedef struct {ty} {ty};"), decl.span, "interface");
        }
        self.emit("");

        for name in &order {
            let Some(decl) = self.interfaces.get(name).copied() else {
                continue;
            };
            if decl.visibility != Visibility::Visible {
                continue;
            }
            let ty = self.c_interface(name);
            self.emit_with_span(format!("struct {ty} {{"), decl.span, "interface");
            self.depth += 1;
            if decl.fields.is_empty() {
                self.emit("unsigned char loi_f_empty;");
            }
            for field in &decl.fields {
                let field_ty = self.resolve_type(&field.ty);
                self.emit(format!(
                    "{} {};",
                    self.c_type(&field_ty),
                    self.c_field(&field.name)
                ));
            }
            self.depth -= 1;
            self.emit("};");
            self.emit("");
        }
    }

    fn param_decl(&self, param: &Param) -> String {
        let ty = self.resolve_type(&param.ty);
        let c_type = self.c_type(&ty);
        let name = self.c_local(&param.name);
        match param.direction {
            Direction::In => format!("{c_type} {name}"),
            Direction::Out | Direction::Inout => format!("{c_type}* {name}"),
        }
    }

    fn param_list(&self, params: &[Param]) -> String {
        if params.is_empty() {
            "void".to_string()
        } else {
            params
                .iter()
                .map(|param| self.param_decl(param))
                .collect::<Vec<_>>()
                .join(", ")
        }
    }

    fn function_return_ty(&self, name: &str) -> Ty {
        if let Some(ty) = self.intrinsic_return_ty.get(name) {
            return ty.clone();
        }
        self.functions
            .get(name)
            .and_then(|decl| decl.return_type.as_ref())
            .map(|ty| self.resolve_type(ty))
            .unwrap_or(Ty::Void)
    }

    fn field_ty(&self, interface: &str, field: &str) -> Option<Ty> {
        self.interfaces
            .get(interface)
            .and_then(|decl| decl.fields.iter().find(|candidate| candidate.name == field))
            .map(|decl| self.resolve_type(&decl.ty))
    }

    fn emit_prototypes(&mut self) {
        let order = self.function_order.clone();
        let subset = self.defined.is_some();
        for name in &order {
            let Some(decl) = self.functions.get(name).copied() else {
                continue;
            };
            if name == "main" {
                self.emit_with_span("int main(void);", decl.span, "function");
            } else if decl.external || subset || decl.visibility == Visibility::Visible {
                let ret = self.c_type(&self.function_return_ty(name));
                let params = self.param_list(&decl.params);
                self.emit_with_span(
                    format!("{ret} {}({params});", self.c_func(name)),
                    decl.span,
                    "function",
                );
            } else {
                let ret = self.c_type(&self.function_return_ty(name));
                let params = self.param_list(&decl.params);
                self.emit(format!(
                    "static inline {ret} {}({params});",
                    self.c_func(name)
                ));
            }
        }
        self.emit("");
    }

    /// Emit function prototypes for `visible` functions only (header).
    /// `main` is always included since it is the program entry point.
    fn emit_prototypes_visible(&mut self) {
        let order = self.function_order.clone();
        for name in &order {
            let Some(decl) = self.functions.get(name).copied() else {
                continue;
            };
            if name == "main" {
                self.emit_with_span("int main(void);", decl.span, "function");
                continue;
            }
            if decl.external || decl.visibility != Visibility::Visible {
                continue;
            }
            let ret = self.c_type(&self.function_return_ty(name));
            let params = self.param_list(&decl.params);
            self.emit_with_span(
                format!("{ret} {}({params});", self.c_func(name)),
                decl.span,
                "function",
            );
        }
    }

    fn emit_functions(&mut self) {
        let order = self.function_order.clone();
        for name in &order {
            let local = self
                .defined
                .as_ref()
                .is_none_or(|defined| defined.contains(name));
            if local {
                self.emit_function(name);
            }
        }
    }

    fn emit_function(&mut self, name: &str) {
        let Some(decl) = self.functions.get(name).copied() else {
            return;
        };
        if decl.external {
            return;
        }

        self.scopes.clear();
        self.protect_saves.clear();
        self.loop_bases.clear();
        self.scopes.push(HashMap::new());
        self.current_function = name.to_string();

        for param in &decl.params {
            let ty = self.resolve_type(&param.ty);
            let repr = match param.direction {
                Direction::In => Repr::Value,
                Direction::Out | Direction::Inout => Repr::Pointer,
            };
            self.declare_var(&param.name, ty, repr);
        }

        let (ret, prefix) = if name == "main" {
            ("int".to_string(), "")
        } else if decl.visibility == Visibility::Visible || self.defined.is_some() {
            (self.c_type(&self.function_return_ty(name)), "")
        } else {
            (
                self.c_type(&self.function_return_ty(name)),
                "static inline ",
            )
        };
        let params = self.param_list(&decl.params);
        self.emit_with_span(
            format!("{prefix}{ret} {}({params})", self.c_func(name)),
            decl.span,
            "function",
        );
        self.emit_open("");
        self.emit_out_defaults(decl);
        self.gen_block(&decl.body);
        if name == "main" {
            self.emit("return 0;");
        }
        self.emit_close();
        self.emit("");

        self.scopes.clear();
        self.protect_saves.clear();
        self.loop_bases.clear();
    }

    /// Apply interface field defaults to `out` composite parameters.
    ///
    /// The reference program relies on `World.tick = 0` even though its
    /// `world_new` only writes some fields. Starting the destination from its
    /// defaults makes that behavior explicit.
    fn emit_out_defaults(&mut self, decl: &'a FunctionDecl) {
        for param in &decl.params {
            if param.direction != Direction::Out {
                continue;
            }
            let ty = self.resolve_type(&param.ty);
            let name = self.c_local(&param.name);
            match ty {
                Ty::Named(interface) => {
                    let literal = self.default_interface_literal(&interface);
                    self.emit(format!("*{name} = {literal};"));
                }
                Ty::Slice(_) => {
                    self.emit(format!("*{name} = (LoiSlice){{0}};"));
                }
                _ => {}
            }
        }
    }

    // ------------------------------------------------------------------
    // Scopes and variable representation
    // ------------------------------------------------------------------

    fn declare_var(&mut self, name: &str, ty: Ty, repr: Repr) {
        if let Some(scope) = self.scopes.last_mut() {
            scope.insert(name.to_string(), VarInfo { ty, repr });
        }
    }

    fn lookup_var(&self, name: &str) -> Option<&VarInfo> {
        self.scopes.iter().rev().find_map(|scope| scope.get(name))
    }

    fn global_ty(&self, name: &str) -> Option<Ty> {
        self.globals.get(name).map(|decl| {
            decl.ty
                .as_ref()
                .map(|ty| self.resolve_type(ty))
                .unwrap_or_else(|| self.ty_of(&decl.value).concretize())
        })
    }

    fn var_ref(&self, name: &str) -> String {
        let c_name = self.c_local(name);
        match self.lookup_var(name) {
            Some(info) if info.repr == Repr::Pointer => format!("(*{c_name})"),
            Some(_) => c_name,
            None => self.c_global(name),
        }
    }

    // ------------------------------------------------------------------
    // Statements
    // ------------------------------------------------------------------

    fn gen_block(&mut self, block: &Block) {
        self.scopes.push(HashMap::new());
        self.emit_open("");
        for statement in &block.statements {
            self.gen_stmt(statement);
        }
        self.emit_close();
        self.scopes.pop();
    }

    fn gen_stmt(&mut self, statement: &Stmt) {
        match &statement.kind {
            StmtKind::Let {
                name, ty, value, ..
            } => {
                let declared = ty.as_ref().map(|ty| self.resolve_type(ty));
                let value_ty = value.as_ref().map(|value| self.ty_of(value));
                let resolved = match (declared, value_ty) {
                    (Some(declared), _) => declared,
                    (None, Some(value_ty)) => value_ty.concretize(),
                    (None, None) => Ty::Error,
                };
                let initializer = value
                    .as_ref()
                    .map(|value| self.gen_coerced_expr(value, &resolved));
                let c_type = self.c_type(&resolved);
                let c_name = self.c_local(name);
                match initializer {
                    Some(value) => self.emit(format!("{c_type} {c_name} = {value};")),
                    None => self.emit(format!("{c_type} {c_name};")),
                }
                self.declare_var(name, resolved, Repr::Value);
            }
            StmtKind::Assign { target, op, value } => {
                let target_ty = self.ty_of(target);
                let target = self.gen_expr(target);
                let value = self.gen_coerced_expr(value, &target_ty);
                if matches!(op, AssignOp::Assign) {
                    self.emit(format!("{target} = {value};"));
                } else {
                    let (helper, operator) = match op {
                        AssignOp::Add => ("add", "+"),
                        AssignOp::Sub => ("sub", "-"),
                        AssignOp::Mul => ("mul", "*"),
                        AssignOp::Div => ("div", "/"),
                        AssignOp::Assign => unreachable!(),
                    };
                    let result_ty = target_ty.concretize();
                    let call = match integer_suffix(&result_ty) {
                        Some(suffix)
                            if matches!(op, AssignOp::Div) || is_signed_integer(&result_ty) =>
                        {
                            format!(
                                "loi_{helper}_{suffix}({target}, {value}, {}, {})",
                                statement.span.line, statement.span.column
                            )
                        }
                        Some(_) => {
                            let c_type = self.c_type(&result_ty);
                            format!("(({c_type})(({target}) {operator} ({value})))")
                        }
                        None => format!("({target} {operator} {value})"),
                    };
                    self.emit(format!("{target} = {call};"));
                }
            }
            StmtKind::Expr(expr) => {
                if let ExprKind::Alloc {
                    target,
                    element_type,
                    count,
                } = &expr.kind
                {
                    self.gen_alloc(expr.span, target, element_type, count);
                } else {
                    let value = self.gen_expr(expr);
                    self.emit(format!("(void)({value});"));
                }
            }
            StmtKind::If {
                condition,
                then_block,
                else_branch,
            } => {
                let condition = self.gen_expr(condition);
                self.emit(format!("if ({condition})"));
                self.gen_block(then_block);
                if let Some(else_branch) = else_branch {
                    self.emit("else");
                    match else_branch {
                        ElseBranch::Block(block) => self.gen_block(block),
                        ElseBranch::If(inner) => self.gen_stmt(inner),
                    }
                }
            }
            StmtKind::While { condition, body } => {
                let condition = self.gen_expr(condition);
                self.emit(format!("while ({condition})"));
                self.loop_bases.push(self.protect_saves.len());
                self.gen_block(body);
                self.loop_bases.pop();
            }
            StmtKind::ForRange {
                variable,
                start,
                end,
                body,
            } => {
                let start_ty = self.ty_of(start);
                let end_ty = self.ty_of(end);
                let loop_ty = types::common_numeric(&start_ty, &end_ty)
                    .filter(Ty::is_integer)
                    .map(|ty| ty.concretize())
                    .unwrap_or(Ty::I64);
                // `int64_t` covers every integer width except u64 values above
                // i64::MAX, which need an unsigned induction variable.
                let index_c = if loop_ty == Ty::U64 {
                    "uint64_t"
                } else {
                    "int64_t"
                };
                let start = self.gen_expr(start);
                let end = self.gen_expr(end);
                let end_temp = self.fresh("end");
                self.emit_open("");
                self.emit(format!("{index_c} {end_temp} = ({index_c})({end});"));

                let c_var = if variable.as_str() == "_" {
                    self.fresh("index")
                } else {
                    self.c_local(variable)
                };
                self.emit(format!(
                    "for ({index_c} {c_var} = ({index_c})({start}); {c_var} < {end_temp}; {c_var}++) {{"
                ));
                self.depth += 1;
                self.scopes.push(HashMap::new());
                if variable.as_str() != "_" {
                    self.declare_var(variable, loop_ty, Repr::Value);
                }
                self.loop_bases.push(self.protect_saves.len());
                for statement in &body.statements {
                    self.gen_stmt(statement);
                }
                self.loop_bases.pop();
                self.scopes.pop();
                self.depth -= 1;
                self.emit("}");
                self.emit_close();
            }
            StmtKind::ForEach {
                direction,
                variable,
                iterable,
                body,
            } => {
                let iterable_ty = self.ty_of(iterable);
                let element_ty = match iterable_ty {
                    Ty::Slice(element) => *element,
                    _ => Ty::Error,
                };
                let iterable = self.gen_expr(iterable);
                let slice_temp = self.fresh("slice");
                let index_temp = self.fresh("index");
                let element_c = self.c_type(&element_ty);

                self.emit_open("");
                self.emit(format!("LoiSlice {slice_temp} = {iterable};"));
                self.emit(format!(
                    "for (size_t {index_temp} = 0; {index_temp} < {slice_temp}.len; {index_temp}++) {{"
                ));
                self.depth += 1;
                self.scopes.push(HashMap::new());
                if variable.as_str() != "_" {
                    let c_var = self.c_local(variable);
                    if *direction == Direction::Inout {
                        self.emit(format!(
                            "{element_c}* {c_var} = &((({element_c}*){slice_temp}.data)[{index_temp}]);"
                        ));
                        self.declare_var(variable, element_ty, Repr::Pointer);
                    } else {
                        self.emit(format!(
                            "{element_c} {c_var} = (({element_c}*){slice_temp}.data)[{index_temp}];"
                        ));
                        self.declare_var(variable, element_ty, Repr::Value);
                    }
                }
                self.loop_bases.push(self.protect_saves.len());
                for statement in &body.statements {
                    self.gen_stmt(statement);
                }
                self.loop_bases.pop();
                self.scopes.pop();
                self.depth -= 1;
                self.emit("}");
                self.emit_close();
            }
            StmtKind::Protect(block) => {
                self.scopes.push(HashMap::new());
                self.emit_open("");
                let save = self.fresh("arena");
                self.emit(format!("size_t {save} = loi_arena_top;"));
                self.protect_saves.push(save.clone());
                for statement in &block.statements {
                    self.gen_stmt(statement);
                }
                self.protect_saves.pop();
                self.emit(format!("loi_arena_top = {save};"));
                self.emit_close();
                self.scopes.pop();
            }
            StmtKind::Return(value) => {
                let expected = self.function_return_ty(&self.current_function);
                let value_ty = value.as_ref().map(|value| {
                    if matches!(expected, Ty::CStr) {
                        expected.clone()
                    } else {
                        self.ty_of(value)
                    }
                });
                let value = value
                    .as_ref()
                    .map(|value| self.gen_coerced_expr(value, &expected));
                match value {
                    Some(value) => {
                        let temp = self.fresh("ret");
                        let temp_ty = value_ty.unwrap_or(Ty::Error).concretize();
                        self.emit(format!("{} {temp} = {value};", self.c_type(&temp_ty)));
                        self.restore_protects(0);
                        self.emit(format!("return {temp};"));
                    }
                    None => {
                        self.restore_protects(0);
                        if self.current_function == "main" {
                            self.emit("return 0;");
                        } else {
                            self.emit("return;");
                        }
                    }
                }
            }
            StmtKind::Continue => {
                let base = self.loop_bases.last().copied().unwrap_or(0);
                self.restore_protects(base);
                self.emit("continue;");
            }
            StmtKind::Break => {
                let base = self.loop_bases.last().copied().unwrap_or(0);
                self.restore_protects(base);
                self.emit("break;");
            }
        }
    }

    fn gen_alloc(&mut self, span: Span, target: &Expr, element_type: &Type, count: &Expr) {
        let element_ty = self.resolve_type(element_type);
        let element_c = self.c_type(&element_ty);

        // Sequence the operands explicitly instead of relying on C's
        // unspecified evaluation order: capture the target address first, then
        // evaluate the count exactly once, then allocate and store.
        let target_ty = self.ty_of(target);
        let target_c = self.c_type(&target_ty);
        let target = self.gen_expr(target);
        let target_ptr = self.fresh("alloc_target");
        self.emit(format!("{target_c}* {target_ptr} = &({target});"));

        let count = self.gen_expr(count);
        let count_temp = self.fresh("alloc_count");
        self.emit(format!("size_t {count_temp} = (size_t)({count});"));

        self.emit(format!(
            "*{target_ptr} = loi_alloc_slice({count_temp}, sizeof({element_c}), {line}, {column});",
            target_ptr = target_ptr,
            count_temp = count_temp,
            element_c = element_c,
            line = span.line,
            column = span.column,
        ));
    }

    fn restore_protects(&mut self, from: usize) {
        let saves = self.protect_saves[from..]
            .iter()
            .rev()
            .cloned()
            .collect::<Vec<_>>();
        for save in saves {
            self.emit(format!("loi_arena_top = {save};"));
        }
    }

    // ------------------------------------------------------------------
    // Expressions
    // ------------------------------------------------------------------

    fn ty_of(&self, expr: &Expr) -> Ty {
        match &expr.kind {
            ExprKind::Int(_) => Ty::IntLiteral,
            ExprKind::Float(_) => Ty::FloatLiteral,
            ExprKind::Bool(_) => Ty::Bool,
            ExprKind::String(_) => Ty::Slice(Box::new(Ty::U8)),
            ExprKind::SliceLiteral {
                element_type,
                elements,
            } => {
                let element = element_type
                    .as_ref()
                    .map(|ty| self.resolve_type(ty))
                    .or_else(|| {
                        elements
                            .iter()
                            .map(|element| self.ty_of(element))
                            .reduce(|left, right| {
                                types::common_numeric(&left, &right)
                                    .filter(|ty| !ty.is_error())
                                    .or_else(|| (left == right).then_some(left))
                                    .unwrap_or(Ty::Error)
                            })
                            .map(|ty| ty.concretize())
                    })
                    .unwrap_or(Ty::Error);
                Ty::Slice(Box::new(element))
            }
            ExprKind::Ident(name) => self
                .lookup_var(name)
                .map(|info| info.ty.clone())
                .or_else(|| self.global_ty(name))
                .unwrap_or(Ty::Error),
            ExprKind::InterfaceLiteral { name, .. } => Ty::Named(name.clone()),
            ExprKind::Unary { op, operand } => match op {
                UnaryOp::Neg => self.ty_of(operand),
                UnaryOp::Not => Ty::Bool,
            },
            ExprKind::Binary { op, left, right } => match op {
                BinaryOp::Or
                | BinaryOp::And
                | BinaryOp::Eq
                | BinaryOp::Neq
                | BinaryOp::Lt
                | BinaryOp::Lte
                | BinaryOp::Gt
                | BinaryOp::Gte => Ty::Bool,
                BinaryOp::Add | BinaryOp::Sub | BinaryOp::Mul | BinaryOp::Div | BinaryOp::Mod => {
                    types::common_numeric(&self.ty_of(left), &self.ty_of(right))
                        .unwrap_or(Ty::Error)
                }
            },
            ExprKind::Cast { ty, .. } => self.resolve_type(ty),
            ExprKind::Call { callee, .. } => {
                if let ExprKind::Ident(name) = &callee.kind {
                    self.function_return_ty(name)
                } else {
                    Ty::Error
                }
            }
            ExprKind::Alloc { .. } => Ty::Void,
            ExprKind::Move(value) | ExprKind::Copy(value) => self.ty_of(value),
            ExprKind::Member { base, field } => match self.ty_of(base) {
                Ty::Named(interface) => self.field_ty(&interface, field).unwrap_or(Ty::Error),
                Ty::Slice(_) if field == "len" => Ty::U64,
                _ => Ty::Error,
            },
            ExprKind::Index { base, .. } => match self.ty_of(base) {
                Ty::Slice(element) => *element,
                _ => Ty::Error,
            },
        }
    }

    fn gen_expr(&mut self, expr: &Expr) -> String {
        match &expr.kind {
            ExprKind::Int(value) => c_int_literal(value),
            ExprKind::Float(value) => c_float_literal(value),
            ExprKind::Bool(value) => value.to_string(),
            ExprKind::String(text) => {
                let index = self.string_index(text);
                format!("(LoiSlice){{ (void*)loi_str_{index}, {} }}", text.len())
            }
            ExprKind::SliceLiteral {
                element_type,
                elements,
            } => {
                let element_ty = match self.ty_of(expr) {
                    Ty::Slice(element) => *element,
                    _ => element_type
                        .as_ref()
                        .map(|ty| self.resolve_type(ty))
                        .unwrap_or(Ty::Error),
                };
                if elements.is_empty() {
                    "(LoiSlice){ NULL, 0 }".to_string()
                } else {
                    let element_c = self.c_type(&element_ty);
                    let values = elements
                        .iter()
                        .map(|element| self.gen_expr(element))
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!(
                        "(LoiSlice){{ (void*)({element_c}[]){{ {values} }}, {} }}",
                        elements.len()
                    )
                }
            }
            ExprKind::Ident(name) => self.var_ref(name),
            ExprKind::InterfaceLiteral { name, fields } => {
                self.interface_literal_code(name, fields)
            }
            ExprKind::Unary { op, operand } => {
                let operand_ty = self.ty_of(operand).concretize();
                let operand = self.gen_expr(operand);
                match op {
                    UnaryOp::Neg => {
                        if let Some(suffix) = integer_suffix(&operand_ty) {
                            if is_signed_integer(&operand_ty) {
                                format!(
                                    "loi_neg_{suffix}({operand}, {}, {})",
                                    expr.span.line, expr.span.column
                                )
                            } else {
                                let c_type = self.c_type(&operand_ty);
                                format!("(({c_type})(-({c_type})({operand})))")
                            }
                        } else {
                            format!("(-{operand})")
                        }
                    }
                    UnaryOp::Not => format!("(!{operand})"),
                }
            }
            ExprKind::Binary { op, left, right } => {
                let left_ty = self.ty_of(left);
                let right_ty = self.ty_of(right);
                let left = self.gen_expr(left);
                let right = self.gen_expr(right);
                if matches!(op, BinaryOp::Eq | BinaryOp::Neq) && matches!(left_ty, Ty::Slice(_)) {
                    let call = format!("loi_slice_eq({left}, {right})");
                    return if *op == BinaryOp::Eq {
                        call
                    } else {
                        format!("(!{call})")
                    };
                }
                let operator = match op {
                    BinaryOp::Or => "||",
                    BinaryOp::And => "&&",
                    BinaryOp::Eq => "==",
                    BinaryOp::Neq => "!=",
                    BinaryOp::Lt => "<",
                    BinaryOp::Lte => "<=",
                    BinaryOp::Gt => ">",
                    BinaryOp::Gte => ">=",
                    BinaryOp::Add => "+",
                    BinaryOp::Sub => "-",
                    BinaryOp::Mul => "*",
                    BinaryOp::Div => "/",
                    BinaryOp::Mod => "%",
                };
                let result_ty = types::common_numeric(&left_ty, &right_ty)
                    .unwrap_or(Ty::Error)
                    .concretize();
                let helper = match op {
                    BinaryOp::Add => Some("add"),
                    BinaryOp::Sub => Some("sub"),
                    BinaryOp::Mul => Some("mul"),
                    BinaryOp::Div => Some("div"),
                    BinaryOp::Mod => Some("rem"),
                    BinaryOp::Or
                    | BinaryOp::And
                    | BinaryOp::Eq
                    | BinaryOp::Neq
                    | BinaryOp::Lt
                    | BinaryOp::Lte
                    | BinaryOp::Gt
                    | BinaryOp::Gte => None,
                };
                if let Some(helper) = helper
                    && let Some(suffix) = integer_suffix(&result_ty)
                {
                    let checked = matches!(op, BinaryOp::Div | BinaryOp::Mod)
                        || is_signed_integer(&result_ty);
                    if checked {
                        return format!(
                            "loi_{helper}_{suffix}({left}, {right}, {}, {})",
                            expr.span.line, expr.span.column
                        );
                    }
                    let c_type = self.c_type(&result_ty);
                    return format!("(({c_type})(({left}) {operator} ({right})))");
                }
                format!("({left} {operator} {right})")
            }
            ExprKind::Cast { expr: inner, ty } => {
                let inner = self.gen_expr(inner);
                let ty = self.c_type(&self.resolve_type(ty));
                format!("(({ty}){inner})")
            }
            ExprKind::Call { callee, args } => self.gen_call(callee, args),
            ExprKind::Alloc {
                target,
                element_type,
                count,
            } => {
                let target = self.gen_expr(target);
                let element_c = self.c_type(&self.resolve_type(element_type));
                let count = self.gen_expr(count);
                format!(
                    "(({target}) = loi_alloc_slice((size_t)({count}), sizeof({element_c}), {}, {}))",
                    expr.span.line, expr.span.column
                )
            }
            ExprKind::Move(value) | ExprKind::Copy(value) => self.gen_expr(value),
            ExprKind::Member { base, field } => {
                if field == "len" && matches!(self.ty_of(base), Ty::Slice(_)) {
                    let base = self.gen_expr(base);
                    return format!("((uint64_t)({base}).len)");
                }
                let base = self.gen_expr(base);
                format!("({base}).{}", self.c_field(field))
            }
            ExprKind::Index { base, index } => {
                let element_ty = match self.ty_of(base) {
                    Ty::Slice(element) => *element,
                    _ => Ty::Error,
                };
                let element_c = self.c_type(&element_ty);
                let base = self.gen_expr(base);
                let index = self.gen_expr(index);
                format!(
                    "(*({element_c}*)loi_index(({base}), (size_t)({index}), sizeof({element_c}), {}, {}))",
                    expr.span.line, expr.span.column
                )
            }
        }
    }

    /// Generate an expression in a context expecting `expected`. The only
    /// coercion is a string literal becoming a NUL-terminated `cstr`.
    fn gen_coerced_expr(&mut self, expr: &Expr, expected: &Ty) -> String {
        if matches!(expected, Ty::CStr)
            && let ExprKind::String(text) = &expr.kind
        {
            let index = self.string_index(text);
            return format!("((const char*)loi_str_{index})");
        }
        self.gen_expr(expr)
    }

    fn gen_call(&mut self, callee: &Expr, args: &[CallArg]) -> String {
        let ExprKind::Ident(name) = &callee.kind else {
            return "/* unsupported call target */ 0".to_string();
        };

        // Intrinsics map directly to C library calls instead of user functions.
        if !self.functions.contains_key(name)
            && let Some(c_code) = self.gen_intrinsic_call(name, args, callee.span)
        {
            return c_code;
        }

        let params = self
            .functions
            .get(name)
            .map(|decl| {
                decl.params
                    .iter()
                    .map(|param| (param.direction, self.resolve_type(&param.ty)))
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();

        let mut lowered = Vec::new();
        for (index, arg) in args.iter().enumerate() {
            let (direction, expected) = params
                .get(index)
                .cloned()
                .unwrap_or((arg.direction, Ty::Error));
            let value = self.gen_coerced_expr(&arg.value, &expected);
            match direction {
                Direction::In => lowered.push(value),
                Direction::Out | Direction::Inout => lowered.push(format!("&({value})")),
            }
        }

        format!("{}({})", self.c_func(name), lowered.join(", "))
    }

    /// Generate C for a built-in intrinsic call. Returns `None` for user
    /// functions. Intrinsics are defined in the checker's `collect_names`;
    //  their C mappings are temporary pending resolution of spec question 9.
    fn gen_intrinsic_call(&mut self, name: &str, args: &[CallArg], _span: Span) -> Option<String> {
        match name {
            "print" | "eprint" => {
                let arg = args.first()?;
                let value = self.gen_expr(&arg.value);
                // Capture the slice in a temporary so it is evaluated once.
                let temp = self.fresh("print_arg");
                let slice_ty = self.ty_of(&arg.value);
                let slice_c = self.c_type(&slice_ty);
                self.emit(format!("{slice_c} {temp} = {value};"));
                let stream = if name == "print" { "stdout" } else { "stderr" };
                Some(format!("fwrite({temp}.data, 1, {temp}.len, {stream})"))
            }
            "len" => {
                let arg = args.first()?;
                let value = self.gen_expr(&arg.value);
                let temp = self.fresh("len_arg");
                let slice_ty = self.ty_of(&arg.value);
                let slice_c = self.c_type(&slice_ty);
                self.emit(format!("{slice_c} {temp} = {value};"));
                Some(format!("((uint64_t){temp}.len)"))
            }
            "panic" => {
                let arg = args.first()?;
                let value = self.gen_expr(&arg.value);
                let temp = self.fresh("panic_arg");
                let slice_ty = self.ty_of(&arg.value);
                let slice_c = self.c_type(&slice_ty);
                self.emit(format!("{slice_c} {temp} = {value};"));
                Some(format!(
                    "fwrite({temp}.data, 1, {temp}.len, stderr), exit(1)"
                ))
            }
            "sqrt" | "floor" | "ceil" | "fabs" => {
                let arg = args.first()?;
                let value = self.gen_expr(&arg.value);
                Some(format!("{name}({value})"))
            }
            "pow" | "fmod" => {
                let left = self.gen_expr(&args.first()?.value);
                let right = self.gen_expr(&args.get(1)?.value);
                Some(format!("{name}({left}, {right})"))
            }
            _ => None,
        }
    }

    fn interface_literal_code(&mut self, name: &str, fields: &[FieldInit]) -> String {
        let declared = self
            .interfaces
            .get(name)
            .map(|decl| decl.fields.clone())
            .unwrap_or_default();
        let mut initializers = Vec::new();
        for field in &declared {
            let field_ty = self.resolve_type(&field.ty);
            let value = if let Some(init) = fields.iter().find(|init| init.name == field.name) {
                Some(self.gen_coerced_expr(&init.value, &field_ty))
            } else {
                field
                    .default
                    .as_ref()
                    .map(|value| self.gen_coerced_expr(value, &field_ty))
            };
            if let Some(value) = value {
                initializers.push(format!(".{} = {value}", self.c_field(&field.name)));
            }
        }

        let ty = self.c_interface(name);
        if initializers.is_empty() {
            format!("({ty}){{0}}")
        } else {
            format!("({ty}){{ {} }}", initializers.join(", "))
        }
    }

    fn default_interface_literal(&mut self, name: &str) -> String {
        self.interface_literal_code(name, &[])
    }
}

/// Collect every string literal in a program in first-seen order.
fn collect_program_strings(
    program: &Program,
    indices: &mut HashMap<String, usize>,
    order: &mut Vec<String>,
) {
    for item in &program.items {
        match item {
            Item::Import(_) => {}
            Item::Interface(decl) => {
                for field in &decl.fields {
                    if let Some(default) = &field.default {
                        collect_expr_strings(default, indices, order);
                    }
                }
            }
            Item::Opaque(_) => {}
            Item::Global(decl) => collect_expr_strings(&decl.value, indices, order),
            Item::Function(decl) => collect_block_strings(&decl.body, indices, order),
        }
    }
}

fn collect_block_strings(
    block: &Block,
    indices: &mut HashMap<String, usize>,
    order: &mut Vec<String>,
) {
    for statement in &block.statements {
        collect_stmt_strings(statement, indices, order);
    }
}

fn collect_stmt_strings(
    statement: &Stmt,
    indices: &mut HashMap<String, usize>,
    order: &mut Vec<String>,
) {
    match &statement.kind {
        StmtKind::Let { value, .. } => {
            if let Some(value) = value {
                collect_expr_strings(value, indices, order);
            }
        }
        StmtKind::Assign { target, value, .. } => {
            collect_expr_strings(target, indices, order);
            collect_expr_strings(value, indices, order);
        }
        StmtKind::Expr(expr) => collect_expr_strings(expr, indices, order),
        StmtKind::If {
            condition,
            then_block,
            else_branch,
        } => {
            collect_expr_strings(condition, indices, order);
            collect_block_strings(then_block, indices, order);
            match else_branch {
                Some(ElseBranch::Block(block)) => collect_block_strings(block, indices, order),
                Some(ElseBranch::If(statement)) => collect_stmt_strings(statement, indices, order),
                None => {}
            }
        }
        StmtKind::While { condition, body } => {
            collect_expr_strings(condition, indices, order);
            collect_block_strings(body, indices, order);
        }
        StmtKind::ForRange {
            start, end, body, ..
        } => {
            collect_expr_strings(start, indices, order);
            collect_expr_strings(end, indices, order);
            collect_block_strings(body, indices, order);
        }
        StmtKind::ForEach { iterable, body, .. } => {
            collect_expr_strings(iterable, indices, order);
            collect_block_strings(body, indices, order);
        }
        StmtKind::Protect(block) => collect_block_strings(block, indices, order),
        StmtKind::Return(value) => {
            if let Some(value) = value {
                collect_expr_strings(value, indices, order);
            }
        }
        StmtKind::Continue | StmtKind::Break => {}
    }
}

fn collect_expr_strings(
    expr: &Expr,
    indices: &mut HashMap<String, usize>,
    order: &mut Vec<String>,
) {
    match &expr.kind {
        ExprKind::String(text) => {
            if !indices.contains_key(text) {
                indices.insert(text.clone(), order.len());
                order.push(text.clone());
            }
        }
        ExprKind::SliceLiteral { elements, .. } => {
            for element in elements {
                collect_expr_strings(element, indices, order);
            }
        }
        ExprKind::InterfaceLiteral { fields, .. } => {
            for field in fields {
                collect_expr_strings(&field.value, indices, order);
            }
        }
        ExprKind::Unary { operand, .. }
        | ExprKind::Cast { expr: operand, .. }
        | ExprKind::Move(operand)
        | ExprKind::Copy(operand) => collect_expr_strings(operand, indices, order),
        ExprKind::Binary { left, right, .. } => {
            collect_expr_strings(left, indices, order);
            collect_expr_strings(right, indices, order);
        }
        ExprKind::Call { callee, args } => {
            collect_expr_strings(callee, indices, order);
            for arg in args {
                collect_expr_strings(&arg.value, indices, order);
            }
        }
        ExprKind::Alloc { target, count, .. } => {
            collect_expr_strings(target, indices, order);
            collect_expr_strings(count, indices, order);
        }
        ExprKind::Member { base, .. } => collect_expr_strings(base, indices, order),
        ExprKind::Index { base, index } => {
            collect_expr_strings(base, indices, order);
            collect_expr_strings(index, indices, order);
        }
        ExprKind::Int(_) | ExprKind::Float(_) | ExprKind::Bool(_) | ExprKind::Ident(_) => {}
    }
}

fn integer_suffix(ty: &Ty) -> Option<&'static str> {
    match ty {
        Ty::I8 => Some("i8"),
        Ty::I16 => Some("i16"),
        Ty::I32 => Some("i32"),
        Ty::I64 => Some("i64"),
        Ty::U8 => Some("u8"),
        Ty::U16 => Some("u16"),
        Ty::U32 => Some("u32"),
        Ty::U64 => Some("u64"),
        _ => None,
    }
}

fn is_signed_integer(ty: &Ty) -> bool {
    matches!(ty, Ty::I8 | Ty::I16 | Ty::I32 | Ty::I64)
}

fn c_int_literal(text: &str) -> String {
    let digits = text.replace('_', "");
    // Preserve hex (0x/0X) and binary (0b/0B) prefixes for C; only add
    // suffixes for plain decimal literals.
    if digits.starts_with("0x")
        || digits.starts_with("0X")
        || digits.starts_with("0b")
        || digits.starts_with("0B")
    {
        return digits;
    }
    if let Ok(value) = digits.parse::<u128>() {
        if value > i64::MAX as u128 {
            return format!("{digits}ULL");
        }
        if value > u32::MAX as u128 {
            return format!("{digits}LL");
        }
    }
    digits
}

fn c_float_literal(text: &str) -> String {
    text.replace('_', "")
}

