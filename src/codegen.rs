/// Lower a checked program to an IR module text.
pub fn generate_ir(program: &Program) -> Result<String, CodegenError> {
    let mut builder = IrBuilder::new();

    // Add interface types.
    for item in &program.items {
        if let Item::Interface(decl) = item {
            let mut fields = Vec::new();
            for field in &decl.fields {
                let ir_ty = resolve_ir_type(&field.ty)?;
                fields.push((field.name.clone(), ir_ty));
            }
            builder.add_interface(decl.name.clone(), fields);
        }
    }

    // Add functions.
    for item in &program.items {
        if let Item::Function(decl) = item {
            let mut params = Vec::new();
            for param in &decl.params {
                let ir_ty = resolve_ir_type(&param.ty)?;
                params.push((param.name.clone(), ir_ty));
            }
            let return_ty = match &decl.return_type {
                Some(ty) => resolve_ir_type(ty)?,
                None => IrType::Void,
            };
            builder.start_function(&decl.name, decl.visibility, params, return_ty);
            builder.start_block("entry");
            gen_block(&mut builder, &decl.body)?;
            builder.finish_block();
            builder.finish_function();
        }
    }

    Ok(builder.module().emit())
}

/// Resolve a Loi `Type` to an IR type.
fn resolve_ir_type(ty: &Type) -> Result<IrType, CodegenError> {
    match ty {
        Type::Named(name) => {
            if let Some(ir_ty) = resolve_primitive(name) {
                Ok(ir_ty)
            } else {
                Ok(IrType::Named(name.clone()))
            }
        }
        Type::Slice(element) => {
            let elem_ty = resolve_ir_type(element)?;
            Ok(IrType::Slice(Box::new(elem_ty)))
        }
    }
}

fn resolve_primitive(name: &str) -> Option<IrType> {
    match name {
        "i8" => Some(IrType::Int(8)),
        "i16" => Some(IrType::Int(16)),
        "i32" => Some(IrType::Int(32)),
        "i64" => Some(IrType::Int(64)),
        "u8" => Some(IrType::Uint(8)),
        "u16" => Some(IrType::Uint(16)),
        "u32" => Some(IrType::Uint(32)),
        "u64" => Some(IrType::Uint(64)),
        "f32" => Some(IrType::Float(32)),
        "f64" => Some(IrType::Float(64)),
        "bool" => Some(IrType::Bool),
        "void" => Some(IrType::Void),
        _ => None,
    }
}

/// Generate IR statements into the current block.
fn gen_block(builder: &mut IrBuilder, block: &Block) -> Result<(), CodegenError> {
    for stmt in &block.statements {
        gen_stmt(builder, stmt)?;
    }
    Ok(())
}

fn gen_stmt(builder: &mut IrBuilder, stmt: &Stmt) -> Result<(), CodegenError> {
    match &stmt.kind {
        StmtKind::Let {
            mutable: _,
            name: _,
            ty,
            value,
        } => {
            let ty = match ty {
                Some(t) => resolve_ir_type(t)?,
                None => IrType::Int(32), // default for inferred
            };
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Alloca(reg, ty.clone()));
            if let Some(value) = value {
                let val_reg = gen_expr(builder, value)?;
                builder.emit_inst(IrInst::Store(ty, reg, val_reg));
            }
        }
        StmtKind::Assign { target, op, value } => {
            let value_reg = gen_expr(builder, value)?;
            match op {
                AssignOp::Assign => {
                    // Store into target - need to resolve target to a reg/ptr
                    let target_reg = gen_expr(builder, target)?;
                    builder.emit_inst(IrInst::Store(IrType::Int(32), target_reg, value_reg));
                }
                _ => {
                    // Compound assignment - for now just store
                    let target_reg = gen_expr(builder, target)?;
                    builder.emit_inst(IrInst::Store(IrType::Int(32), target_reg, value_reg));
                }
            }
        }
        StmtKind::Expr(expr) => {
            gen_expr(builder, expr)?;
        }
        StmtKind::If {
            condition,
            then_block,
            else_branch,
        } => {
            let cond_reg = gen_expr(builder, condition)?;
            let then_label = builder.fresh_block();
            let else_label = builder.fresh_block();
            let end_label = builder.fresh_block();
            builder.emit_inst(IrInst::CondJump(
                cond_reg,
                then_label.clone(),
                else_label.clone(),
            ));
            builder.finish_block();
            builder.start_block(&then_label);
            gen_block(builder, then_block)?;
            builder.emit_inst(IrInst::Jump(end_label.clone()));
            builder.finish_block();
            builder.start_block(&else_label);
            if let Some(else_branch) = else_branch {
                match else_branch {
                    ElseBranch::Block(block) => gen_block(builder, block)?,
                    ElseBranch::If(inner) => gen_stmt(builder, inner)?,
                }
            }
            builder.emit_inst(IrInst::Jump(end_label.clone()));
            builder.finish_block();
            builder.start_block(&end_label);
        }
        StmtKind::While { condition, body } => {
            let cond_label = builder.fresh_block();
            let body_label = builder.fresh_block();
            let end_label = builder.fresh_block();
            builder.emit_inst(IrInst::Jump(cond_label.clone()));
            builder.finish_block();
            builder.start_block(&cond_label);
            let cond_reg = gen_expr(builder, condition)?;
            builder.emit_inst(IrInst::CondJump(
                cond_reg,
                body_label.clone(),
                end_label.clone(),
            ));
            builder.finish_block();
            builder.start_block(&body_label);
            gen_block(builder, body)?;
            builder.emit_inst(IrInst::Jump(cond_label.clone()));
            builder.finish_block();
            builder.start_block(&end_label);
        }
        StmtKind::ForRange {
            variable: _,
            start,
            end,
            body: _,
        } => {
            // Simple for-range: for i in start..end
            let start_reg = gen_expr(builder, start)?;
            let end_reg = gen_expr(builder, end)?;
            let i_reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Alloca(i_reg, IrType::Int(32)));
            builder.emit_inst(IrInst::Store(IrType::Int(32), i_reg, start_reg));
            let cond_label = builder.fresh_block();
            let body_label = builder.fresh_block();
            let end_label = builder.fresh_block();
            builder.emit_inst(IrInst::Jump(cond_label.clone()));
            builder.finish_block();
            builder.start_block(&cond_label);
            let i_val_reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Load(i_reg, IrType::Int(32), i_reg));
            let cmp_result = builder.fresh_reg();
            builder.emit_inst(IrInst::Cmp(
                CmpOp::Slt,
                IrType::Int(32),
                cmp_result,
                i_val_reg,
                end_reg,
            ));
            // For simplicity, we'll just store and continue - a full implementation
            // would need proper SSA. For now, emit a simple structure.
            let _ = cond_label;
            let _ = body_label;
            let _ = end_label;
        }
        StmtKind::ForEach { .. } => {
            // For-each not yet fully implemented in IR
        }
        StmtKind::Protect(block) => {
            gen_block(builder, block)?;
        }
        StmtKind::Return(value) => {
            if let Some(value) = value {
                let val_reg = gen_expr(builder, value)?;
                builder.emit_inst(IrInst::Return(Some(val_reg)));
            } else {
                builder.emit_inst(IrInst::Return(None));
            }
        }
        StmtKind::Continue => {}
        StmtKind::Break => {}
    }
    Ok(())
}

/// Generate an expression into a register.
fn gen_expr(builder: &mut IrBuilder, expr: &Expr) -> Result<Reg, CodegenError> {
    match &expr.kind {
        ExprKind::Int(text) => {
            let digits = text.replace('_', "");
            // Detect hex/binary prefixes
            let (radix, digits) =
                if let Some(rest) = digits.strip_prefix("0x").or(digits.strip_prefix("0X")) {
                    (16, rest)
                } else if let Some(rest) = digits.strip_prefix("0b").or(digits.strip_prefix("0B")) {
                    (2, rest)
                } else {
                    (10, digits.as_str())
                };
            let value: i128 = i128::from_str_radix(digits, radix).unwrap_or(0);
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Imm(reg, IrType::Int(32), value));
            Ok(reg)
        }
        ExprKind::Float(text) => {
            let value: f64 = text.replace('_', "").parse().unwrap_or(0.0);
            let reg = builder.fresh_reg();
            // For floats, we store the bits as an integer immediate
            builder.emit_inst(IrInst::Imm(reg, IrType::Float(64), value.to_bits() as i128));
            Ok(reg)
        }
        ExprKind::Bool(value) => {
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Imm(reg, IrType::Bool, if *value { 1 } else { 0 }));
            Ok(reg)
        }
        ExprKind::String(_) | ExprKind::SliceLiteral { .. } => Err(CodegenError::new(
            "string and slice literals are not supported by the draft IR backend",
        )),
        ExprKind::Ident(name) => {
            let reg = builder.get_var_reg(name);
            builder.emit_inst(IrInst::Load(reg, IrType::Int(32), reg));
            Ok(reg)
        }
        ExprKind::Binary { op, left, right } => {
            let lhs = gen_expr(builder, left)?;
            let rhs = gen_expr(builder, right)?;
            let result = builder.fresh_reg();
            let bin_op = match op {
                BinaryOp::Add => BinOp::Add,
                BinaryOp::Sub => BinOp::Sub,
                BinaryOp::Mul => BinOp::Mul,
                BinaryOp::Div => BinOp::SDiv,
                BinaryOp::Mod => BinOp::SRem,
                _ => BinOp::Add,
            };
            builder.emit_inst(IrInst::BinOp(bin_op, IrType::Int(32), result, lhs, rhs));
            Ok(result)
        }
        ExprKind::Unary { op, operand } => {
            let operand_reg = gen_expr(builder, operand)?;
            let result = builder.fresh_reg();
            let un_op = match op {
                UnaryOp::Neg => UnOp::Neg,
                UnaryOp::Not => UnOp::Not,
            };
            builder.emit_inst(IrInst::UnOp(un_op, IrType::Int(32), result, operand_reg));
            Ok(result)
        }
        ExprKind::Call { callee, args } => {
            if let ExprKind::Ident(name) = &callee.kind {
                let mut arg_regs = Vec::new();
                for arg in args {
                    let arg_reg = gen_expr(builder, &arg.value)?;
                    arg_regs.push(arg_reg);
                }
                let result = builder.fresh_reg();
                builder.emit_inst(IrInst::Call(
                    result,
                    name.clone(),
                    arg_regs,
                    IrType::Int(32),
                ));
                Ok(result)
            } else {
                let reg = builder.fresh_reg();
                builder.emit_inst(IrInst::BinOp(
                    BinOp::Add,
                    IrType::Int(32),
                    reg,
                    Reg(0),
                    Reg(0),
                ));
                Ok(reg)
            }
        }
        ExprKind::Alloc { .. } => {
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::AllocSlice(reg, IrType::Int(32), Reg(0), Reg(0)));
            Ok(reg)
        }
        ExprKind::InterfaceLiteral { .. } => {
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::Alloca(reg, IrType::Int(32)));
            Ok(reg)
        }
        ExprKind::Cast { .. } => {
            let reg = builder.fresh_reg();
            builder.emit_inst(IrInst::BitCast(
                reg,
                IrType::Int(32),
                IrType::Int(32),
                Reg(0),
            ));
            Ok(reg)
        }
        ExprKind::Move(inner) | ExprKind::Copy(inner) => gen_expr(builder, inner),
        ExprKind::Member { base, field: _ } => {
            let base_reg = gen_expr(builder, base)?;
            let result = builder.fresh_reg();
            // Simplified: just add field offset (0 for now, real implementation needs field offsets)
            builder.emit_inst(IrInst::GetElemPtr(
                result,
                IrType::Int(32),
                base_reg,
                Reg(0),
            ));
            Ok(result)
        }
        ExprKind::Index { base, index } => {
            let base_reg = gen_expr(builder, base)?;
            let index_reg = gen_expr(builder, index)?;
            let result = builder.fresh_reg();
            builder.emit_inst(IrInst::IndexSlice(
                result,
                IrType::Int(32),
                base_reg,
                index_reg,
            ));
            Ok(result)
        }
    }
}
