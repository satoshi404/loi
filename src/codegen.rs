use crate::types::{self, Ty};

/// A failure that prevents C emission.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    pub message: String,
}

impl CodegenError {
    fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for CodegenError {}

/// Lower a checked program to a C translation unit.
///
/// If `source_map_path` is `Some`, a JSON Lines source map file is written
/// next to the generated C, mapping ranges of generated C lines back to the
/// source Loi positions. Comments `// loi:line:col` are also emitted inline
/// at each mapped position.
pub fn generate_c(
    program: &Program,
    source_map_path: Option<&Path>,
) -> Result<String, CodegenError> {
    Generator::new(program, source_map_path, None).generate()
}

/// Lower a checked program to C, emitting only the declarations whose names
/// are in `defined`. Other declarations are emitted as external prototypes so
/// the resulting object can be linked with sibling objects from a multi-file
/// build.
pub fn generate_c_subset(
    program: &Program,
    source_map_path: Option<&Path>,
    defined: &std::collections::HashSet<String>,
) -> Result<String, CodegenError> {
    Generator::new(program, source_map_path, Some(defined.clone())).generate()
}

/// Lower a checked program to a C header file containing only declarations
/// for `visible` items. This is optional and only emitted when requested
/// via `--emit-h`. `hidden` and unspecified-visibility items are not included.
pub fn generate_header(
    program: &Program,
    source_map_path: Option<&Path>,
) -> Result<String, CodegenError> {
    Generator::new(program, source_map_path, None).generate_header()
}

