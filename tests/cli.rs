fn changing_emit_c_path_forces_rebuild() {
    use std::os::unix::fs::PermissionsExt;

    if !has_c_compiler() {
        eprintln!("skipping changing_emit_c_path_forces_rebuild: no C compiler found");
        return;
    }

    let dir = test_dir("emit-c-switch");
    let input = dir.join("program.loi");
    let executable = dir.join("program");
    let first_c = dir.join("first.c");
    let second_c = dir.join("second.c");
    let wrapper = dir.join("cc-wrapper.sh");
    let log = dir.join("cc.log");
    fs::write(&input, "flow main\n    => i32\n{\n    => 0\n}\n").expect("input should be writable");
    fs::write(
        &wrapper,
        "#!/bin/sh\necho run >> \"$LOI_CC_LOG\"\nexec cc \"$@\"\n",
    )
    .expect("wrapper should be writable");
    fs::set_permissions(&wrapper, fs::Permissions::from_mode(0o755))
        .expect("wrapper should be executable");

    let build = |c_path: &std::path::Path| {
        Command::new(loi())
            .arg("build")
            .arg(&input)
            .arg("-o")
            .arg(&executable)
            .arg("--emit-c")
            .arg(c_path)
            .env("CC", &wrapper)
            .env("LOI_CC_LOG", &log)
            .output()
            .expect("loi should run")
    };

    let first = build(&first_c);
    assert!(
        first.status.success(),
        "first build failed: {}",
        String::from_utf8_lossy(&first.stderr)
    );
    assert_eq!(line_count(&log), 1, "first build should invoke cc once");

    // Make the new retained path look like a valid pre-existing file: only
    // the stamp's recorded path can reveal that it is not the current output.
    fs::write(&second_c, "stale\n").expect("second C path should be writable");
    let second = build(&second_c);
    assert!(
        second.status.success(),
        "second build failed: {}",
        String::from_utf8_lossy(&second.stderr)
    );
    assert_eq!(
        line_count(&log),
        2,
        "switching --emit-c paths should force a rebuild"
    );
    let regenerated = fs::read_to_string(&second_c).expect("second C path should exist");
    let _ = fs::remove_dir_all(&dir);
    assert!(
        regenerated.contains("/* Generated by the Loi compiler. */"),
        "the new --emit-c path should receive the generated C"
    );
}

