use std::fs;
use std::path::PathBuf;
use std::process::Command;

#[cfg(unix)]
use std::os::unix::fs::PermissionsExt;

fn loi() -> &'static str {
    env!("CARGO_BIN_EXE_loi")
}

fn test_dir(name: &str) -> PathBuf {
    let dir = PathBuf::from("/tmp/opencode").join(format!("loi-cli-{}-{name}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("test directory should be creatable");
    dir
}

fn has_tool(tool: &str) -> bool {
    Command::new(tool)
        .arg("--version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

fn has_c_compiler() -> bool {
    has_tool("cc")
}

fn line_count(path: &std::path::Path) -> usize {
    fs::read_to_string(path)
        .map(|text| text.lines().count())
        .unwrap_or(0)
}

#[test]
fn gen_prints_c_to_stdout() {
    let dir = test_dir("gen-stdout");
    let input = dir.join("program.loi");
    fs::write(&input, "flow main\n    => i32\n{\n    => 0\n}\n").expect("input should be writable");

    let output = Command::new(loi())
        .arg("gen")
        .arg(&input)
        .output()
        .expect("loi should run");
    let _ = fs::remove_dir_all(&dir);

    assert!(
        output.status.success(),
        "loi gen failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let c = String::from_utf8(output.stdout).expect("generated C should be UTF-8");
    assert!(c.contains("/* Generated by the Loi compiler. */"));
    assert!(c.contains("int main(void)"));
}

